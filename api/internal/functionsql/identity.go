// Package functionsql owns the database permission boundary for Functions.
// It is separate from the guest package: the customer VM never needs an
// administrative SQL client, a provisioning credential, or the Proxy registry.
package functionsql

import (
	"context"
	"encoding/base64"
	"errors"
	"regexp"
	"strings"

	"github.com/jackc/pgx/v5"
)

var identityPattern = regexp.MustCompile(`^fnc_[a-f0-9]{16}$`)
var projectPattern = regexp.MustCompile(`^prj_[a-f0-9]{16}$`)
var branchPattern = regexp.MustCompile(`^br_[a-f0-9]{16}$`)
var identifierPattern = regexp.MustCompile(`^[a-zA-Z_][a-zA-Z0-9_]{0,62}$`)
var verifierPattern = regexp.MustCompile(`^SCRAM-SHA-256\$4096:[A-Za-z0-9+/]+=*\$[A-Za-z0-9+/]+=*:[A-Za-z0-9+/]+=*$`)

// ValidVerifier accepts the bounded SCRAM format generated by this platform:
// 4096 iterations, a 16-byte salt and two SHA-256 keys. It validates structure,
// not password correspondence; the actual authenticated session is mandatory.
func ValidVerifier(value string) bool {
	if len(value) > 256 || !verifierPattern.MatchString(value) {
		return false
	}
	parts := strings.Split(value, "$")
	if len(parts) != 3 {
		return false
	}
	iterationSalt := strings.Split(parts[1], ":")
	keys := strings.Split(parts[2], ":")
	if len(iterationSalt) != 2 || iterationSalt[0] != "4096" || len(keys) != 2 {
		return false
	}
	for i, encoded := range []string{iterationSalt[1], keys[0], keys[1]} {
		raw, err := base64.StdEncoding.Strict().DecodeString(encoded)
		expected := 32
		if i == 0 {
			expected = 16
		}
		if err != nil || len(raw) != expected {
			return false
		}
	}
	return true
}

// Scope is immutable control metadata. The caller must authenticate project
// access, lock the branch intent and connect to its recorded Writer selector.
// This package neither accepts customer DSNs nor mutates a database lifecycle.
type Scope struct {
	FunctionID string
	ProjectID  string
	BranchID   string
	Database   string
	Schema     string
	// ProvisioningRole is an explicit immutable trusted control principal, never
	// customer input. Empty preserves the legacy no-membership contract. PG16
	// creates one non-inheriting, non-settable ADMIN grant to a CREATEROLE creator;
	// only this exact bootstrap-superuser grant may be admitted when recorded.
	ProvisioningRole string
}

func (s Scope) Validate() error {
	if !identityPattern.MatchString(s.FunctionID) || !projectPattern.MatchString(s.ProjectID) || !branchPattern.MatchString(s.BranchID) || !identifierPattern.MatchString(s.Database) || !identifierPattern.MatchString(s.Schema) || strings.HasPrefix(strings.ToLower(s.Schema), "pg_") || strings.HasPrefix(strings.ToLower(s.Schema), "neon_") || strings.HasPrefix(strings.ToLower(s.Schema), "control_") || s.Schema == "information_schema" {
		return errors.New("invalid immutable Functions SQL scope")
	}
	if s.ProvisioningRole != "" && (!identifierPattern.MatchString(s.ProvisioningRole) || s.ProvisioningRole == s.Role()) {
		return errors.New("invalid immutable Functions SQL provisioning principal")
	}
	return nil
}
func (s Scope) Role() string { return "fn_" + strings.TrimPrefix(s.FunctionID, "fnc_") }
func (s Scope) marker() string {
	marker := "neon-control:function:" + s.ProjectID + ":" + s.BranchID + ":" + s.FunctionID
	if s.ProvisioningRole != "" {
		marker += ":provisioner=" + s.ProvisioningRole
	}
	return marker
}
func quote(value string) string   { return pgx.Identifier{value}.Sanitize() }
func literal(value string) string { return "'" + strings.ReplaceAll(value, "'", "''") + "'" }

// DisableLoginTx changes only the original scoped, non-elevated service role's
// LOGIN admission. It never drops ownership/data, adopts a foreign marker or
// repairs unexpected elevation. Replays keep NOLOGIN; absence is terminal.
func DisableLoginTx(ctx context.Context, tx pgx.Tx, s Scope) error {
	if s.Validate() != nil || s.ProvisioningRole == "" {
		return errors.New("Functions SQL disable scope rejected")
	}
	var trusted bool
	if tx.QueryRow(ctx, `SELECT current_database()=$1 AND session_user::text=$2 AND current_user::text=$2
 AND current_setting('createrole_self_grant')='' AND EXISTS(SELECT 1 FROM pg_roles WHERE rolname=$2 AND NOT rolsuper AND rolcreaterole)`, s.Database, s.ProvisioningRole).Scan(&trusted) != nil || !trusted {
		return errors.New("Functions SQL disable principal rejected")
	}
	if _, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock(hashtextextended($1,922743))`, s.FunctionID); err != nil {
		return errors.New("Functions SQL disable unavailable")
	}
	var marker string
	err := tx.QueryRow(ctx, `SELECT COALESCE(shobj_description(oid,'pg_authid'),'') FROM pg_roles WHERE rolname=$1`, s.Role()).Scan(&marker)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil
	}
	if err != nil || marker != s.marker() || verifyRole(ctx, tx, s) != nil {
		return errors.New("Functions SQL disable identity rejected")
	}
	if _, err = tx.Exec(ctx, "ALTER ROLE "+quote(s.Role())+" NOLOGIN"); err != nil {
		return errors.New("Functions SQL disable unavailable")
	}
	return nil
}

// ProvisionTx grants DML on existing ordinary tables and sequences in exactly
// one explicitly selected schema. It does not grant ownership, CREATE, role
// membership, functions/views, BYPASSRLS or database administration. New tables
// require a new owner-authorized reconciliation; no blanket default privileges
// are installed on behalf of customer owners. All failures roll back with the
// caller transaction, including a role unexpectedly present on another branch.
func ProvisionTx(ctx context.Context, tx pgx.Tx, s Scope, verifier string) error {
	if s.Validate() != nil || !ValidVerifier(verifier) {
		return errors.New("Functions SQL scope or SCRAM verifier rejected")
	}
	var database string
	if err := tx.QueryRow(ctx, `SELECT current_database()`).Scan(&database); err != nil || database != s.Database {
		return errors.New("Functions SQL database identity mismatch")
	}
	if s.ProvisioningRole != "" {
		var trusted bool
		// Do not SET ROLE or rewrite the creator's GUC to pass. Extra self grants
		// would create a different permission contract and must fail before DDL.
		err := tx.QueryRow(ctx, `SELECT session_user::text=$1 AND current_user::text=$1
 AND current_setting('createrole_self_grant')=''
 AND EXISTS(SELECT 1 FROM pg_roles WHERE rolname=$1 AND NOT rolsuper AND rolcreaterole)`, s.ProvisioningRole).Scan(&trusted)
		if err != nil || !trusted {
			return errors.New("Functions SQL provisioning principal rejected")
		}
	}
	if _, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock(hashtextextended($1,922743))`, s.FunctionID); err != nil {
		return err
	}
	var exists bool
	if err := tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM pg_namespace WHERE nspname=$1)`, s.Schema).Scan(&exists); err != nil {
		return err
	}
	if !exists {
		return errors.New("Functions target schema must already exist")
	}
	role := s.Role()
	var marker string
	err := tx.QueryRow(ctx, `SELECT COALESCE(shobj_description(oid,'pg_authid'),'') FROM pg_roles WHERE rolname=$1`, role).Scan(&marker)
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		return err
	}
	if err == nil && marker != s.marker() {
		return errors.New("Functions SQL role ownership conflict")
	}
	if errors.Is(err, pgx.ErrNoRows) {
		if _, err = tx.Exec(ctx, "CREATE ROLE "+quote(role)+" NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS"); err != nil {
			return err
		}
		if _, err = tx.Exec(ctx, "COMMENT ON ROLE "+quote(role)+" IS "+literal(s.marker())); err != nil {
			return err
		}
	}
	// Test flags before ALTER: never silently repair or adopt an elevated role.
	if err = verifyRole(ctx, tx, s); err != nil {
		return err
	}
	for _, statement := range []string{
		"GRANT CONNECT ON DATABASE " + quote(s.Database) + " TO " + quote(role),
		"GRANT USAGE ON SCHEMA " + quote(s.Schema) + " TO " + quote(role),
		"ALTER ROLE " + quote(role) + " LOGIN PASSWORD " + literal(verifier) + " CONNECTION LIMIT 4",
		"ALTER ROLE " + quote(role) + " SET search_path=" + quote(s.Schema) + ",pg_catalog",
		"ALTER ROLE " + quote(role) + " SET idle_session_timeout='5s'",
		"ALTER ROLE " + quote(role) + " SET statement_timeout='30s'",
	} {
		if _, err = tx.Exec(ctx, statement); err != nil {
			return err
		}
	}
	rows, err := tx.Query(ctx, `SELECT c.relname,c.relkind::text FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname=$1 AND c.relkind IN ('r','p','S') ORDER BY c.relname`, s.Schema)
	if err != nil {
		return err
	}
	type object struct{ name, kind string }
	var objects []object
	for rows.Next() {
		var o object
		if err = rows.Scan(&o.name, &o.kind); err != nil {
			rows.Close()
			return err
		}
		objects = append(objects, o)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	for _, o := range objects {
		statement := "GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE " + quote(s.Schema) + "." + quote(o.name) + " TO " + quote(role)
		if o.kind == "S" {
			statement = "GRANT USAGE,SELECT ON SEQUENCE " + quote(s.Schema) + "." + quote(o.name) + " TO " + quote(role)
		}
		if _, err = tx.Exec(ctx, statement); err != nil {
			return err
		}
	}
	return verifyRole(ctx, tx, s)
}

func verifyRole(ctx context.Context, tx pgx.Tx, s Scope) error {
	var safe bool
	err := tx.QueryRow(ctx, `SELECT NOT rolsuper AND NOT rolbypassrls AND NOT rolcreatedb AND NOT rolcreaterole AND NOT rolreplication AND NOT rolinherit
 AND ($3='' OR EXISTS(SELECT 1 FROM pg_roles p WHERE p.rolname=$3 AND NOT p.rolsuper AND p.rolcreaterole))
 AND ($3='' OR EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.roleid=pg_roles.oid
 AND m.member=(SELECT oid FROM pg_roles WHERE rolname=$3) AND m.grantor=10
 AND COALESCE((SELECT rolsuper FROM pg_roles WHERE oid=10),false)
 AND m.admin_option AND NOT m.inherit_option AND NOT m.set_option))
 AND NOT EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.member=pg_roles.oid
 OR (m.roleid=pg_roles.oid AND NOT ($3<>'' AND m.member=(SELECT oid FROM pg_roles WHERE rolname=$3)
 AND m.grantor=10 AND COALESCE((SELECT rolsuper FROM pg_roles WHERE oid=10),false)
 AND m.admin_option AND NOT m.inherit_option AND NOT m.set_option)))
 -- '_' is a LIKE wildcard. Match the reserved literal prefix so ordinary
 -- customer schemas such as pgx_private cannot bypass permission inspection.
 AND NOT EXISTS(SELECT 1 FROM pg_namespace n WHERE left(n.nspname,3)<>'pg_' AND n.nspname<>'information_schema' AND has_schema_privilege(pg_roles.oid,n.oid,'CREATE'))
 AND NOT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE left(n.nspname,3)<>'pg_' AND n.nspname<>'information_schema' AND p.prosecdef AND has_function_privilege(pg_roles.oid,p.oid,'EXECUTE'))
 AND NOT EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE left(n.nspname,3)<>'pg_' AND n.nspname<>'information_schema' AND c.relkind IN ('r','p','v','m','f') AND
 (c.relowner=pg_roles.oid
 OR ((n.nspname<>$2 OR c.relkind<>'r') AND (has_table_privilege(pg_roles.oid,c.oid,'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER') OR has_any_column_privilege(pg_roles.oid,c.oid,'SELECT,INSERT,UPDATE,REFERENCES')))
 OR has_table_privilege(pg_roles.oid,c.oid,'TRUNCATE,REFERENCES,TRIGGER,SELECT WITH GRANT OPTION,INSERT WITH GRANT OPTION,UPDATE WITH GRANT OPTION,DELETE WITH GRANT OPTION')
 OR has_any_column_privilege(pg_roles.oid,c.oid,'REFERENCES,SELECT WITH GRANT OPTION,INSERT WITH GRANT OPTION,UPDATE WITH GRANT OPTION')))
 AND NOT EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE left(n.nspname,3)<>'pg_' AND n.nspname<>'information_schema' AND c.relkind='S' AND
 (c.relowner=pg_roles.oid OR (n.nspname<>$2 AND has_sequence_privilege(pg_roles.oid,c.oid,'USAGE,SELECT,UPDATE')) OR has_sequence_privilege(pg_roles.oid,c.oid,'UPDATE,USAGE WITH GRANT OPTION,SELECT WITH GRANT OPTION')))
 -- Trigger execution has its own permission semantics. A grant on an ordinary
 -- table must not implicitly admit customer-installed executable hooks. This
 -- preview rejects all enabled non-internal triggers; disabled hooks require a
 -- new owner-authorized reconciliation before they can be enabled.
 AND NOT EXISTS(SELECT 1 FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
 WHERE n.nspname=$2 AND NOT t.tgisinternal AND t.tgenabled<>'D' AND has_table_privilege(pg_roles.oid,c.oid,'INSERT,UPDATE,DELETE'))
 AND NOT has_database_privilege(pg_roles.oid,current_database(),'CREATE') AND NOT has_database_privilege(pg_roles.oid,current_database(),'TEMP')
 FROM pg_roles WHERE rolname=$1`, s.Role(), s.Schema, s.ProvisioningRole).Scan(&safe)
	if err != nil {
		return err
	}
	if !safe {
		return errors.New("Functions SQL role has inherited or unexpected privileges; database owner must remove broad PUBLIC grants")
	}
	return nil
}
